import csv
import math

import numpy as np
from scipy import stats

Z975 = 1.959963985
MDE80_K = Z975 + stats.norm.ppf(0.80)  # = 2.8016


def ci95(est: float, se: float) -> tuple[float, float]:
    return est - Z975 * se, est + Z975 * se


def mde80(se: float) -> float:
    return MDE80_K * se


def section(title: str) -> None:
    print(f"\n{'=' * 72}\n{title}\n{'=' * 72}")


